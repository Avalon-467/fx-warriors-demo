import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/fx-quota.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {useQuota,callerHash}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync(new URL('../drizzle/0000_clumsy_silver_fox.sql',import.meta.url),'utf8'));
const db={prepare:sql=>({bind:(...args)=>({first:async()=>sqlite.prepare(sql).get(...args)})})};
const attempts=await Promise.allSettled(Array.from({length:20},()=>useQuota(db,'same-bucket',6,Date.now()+3600000)));
assert.equal(attempts.filter(x=>x.status==='fulfilled').length,6);
assert.equal(attempts.filter(x=>x.status==='rejected'&&x.reason.status===429).length,14);
assert.equal(sqlite.prepare('SELECT used FROM fx_usage_counters').get().used,6);
assert.equal(await useQuota(db,'next-bucket',6,Date.now()+3600000),1);
const request=new Request('https://example.com',{headers:{'cf-connecting-ip':'192.0.2.1'}});
assert.equal(await callerHash(request),await callerHash(request));
assert.equal((await callerHash(request)).length,24);
sqlite.close();
console.log('PASS: atomic shared quota caps, independent buckets and daily caller hashing.');
